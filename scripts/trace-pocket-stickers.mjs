// Converts the reference's dark silhouette into transparent, monochrome SVG data.
// Run with the path to an installed Playwright module as the first argument.
import fs from 'node:fs';
import {createHash} from 'node:crypto';
const {chromium}=await import(process.argv[2]||'playwright');
const source='docs/design/retro-pocket-v1/review-set-02/screens/04-goal-settings.png';
const crops={cat:[456,862,128,116],star:[641,862,120,116],flower:[277,1040,116,117],book:[443,1044,139,112],shoe:[635,1044,134,112]};
const browser=await chromium.launch();
try {
  const page=await browser.newPage();
  await page.goto('http://127.0.0.1:6006');
  const data=await page.evaluate(async({source,crops})=>{
    const image=new Image();image.src='/'+source;await image.decode();
    const canvas=document.createElement('canvas');canvas.width=image.width;canvas.height=image.height;
    const ctx=canvas.getContext('2d');ctx.drawImage(image,0,0);
    return Object.fromEntries(Object.entries(crops).map(([id,crop])=>{
      let [x,y,w,h]=crop;
      let pixels=ctx.getImageData(x,y,w,h).data;
      let left=w,right=0,top=h,bottom=0;
      for(let py=0;py<h;py++)for(let px=0;px<w;px++){
        const p=(py*w+px)*4;
        if(.2126*pixels[p]+.7152*pixels[p+1]+.0722*pixels[p+2]<110){left=Math.min(left,px);right=Math.max(right,px);top=Math.min(top,py);bottom=Math.max(bottom,py);}
      }
      x+=left;y+=top;w=right-left+1;h=bottom-top+1;
      pixels=ctx.getImageData(x,y,w,h).data;
      // Fit the ink bounds in a common square without stretching the silhouette.
      const scale=56/Math.max(w,h), ox=(56-w*scale)/2, oy=(56-h*scale)/2;
      const mask=Array.from({length:56},()=>Array(56).fill(false));
      for(let row=0;row<56;row++)for(let col=0;col<56;col++){
        let dark=0,total=0;
        for(let sy=0;sy<4;sy++)for(let sx=0;sx<4;sx++){
          const px=Math.floor((col+(sx+.5)/4-ox)/scale),py=Math.floor((row+(sy+.5)/4-oy)/scale);
          total++;if(px<0||py<0||px>=w||py>=h)continue;
          const p=(py*w+px)*4;
          if(.2126*pixels[p]+.7152*pixels[p+1]+.0722*pixels[p+2]<110)dark++;
        }
        mask[row][col]=dark/total>=.5;
      }
      let path='';
      for(let row=0;row<56;row++)for(let col=0;col<56;col++)if(mask[row][col]){
        const start=col;while(col+1<56&&mask[row][col+1])col++;
        const length=col-start+1;path+=`M${start} ${row}h${length}v1h-${length}Z`;
      }
      return [id,{path,crop:[x,y,w,h]}];
    }));
  },{source,crops});
  const hash=createHash('sha256').update(fs.readFileSync(source)).digest('hex');
  for(const [id,{path,crop}] of Object.entries(data))fs.writeFileSync(`src/stickers/pocket/assets/${id}.ts`,
    `// Generated by scripts/trace-pocket-stickers.mjs. See ../README.md.\nexport const ${id}Asset = ${JSON.stringify({viewBox:'0 0 56 56',path,source:{file:source,crop,sha256:hash},revision:1},null,2)} as const;\n`);
} finally {await browser.close();}
