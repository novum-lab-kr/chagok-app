function carryFace(dots, blocks = 3) {
  const shapes = [shape({...(blocks === 0 ? {10: sym(4)} : {}), 11: sym(8), 12: sym(12), ...range(13, 14, () => sym(14)), ...range(15, 20, () => sym(16)), 21: sym(14)}, 'g')];
  if (blocks >= 1) shapes.push(shape(range(8, 11, () => [8, 15]), 'm'));
  if (blocks >= 2) shapes.push(shape(range(5, 8, () => [9, 16]), 'w'));
  if (blocks >= 3) shapes.push(shape(range(2, 5, () => [7, 14]), 'o'));
  const blush = dots.blush ?? [[6, 16], [7, 16], [16, 16], [17, 16]];
  const out = {'#': [...(dots['#'] || []), [8, 22], [9, 22], [14, 22], [15, 22]], o: [...blush, ...(dots.o || [])]};
  if (dots.w) out.w = dots.w;
  return build(shapes, out);
}
